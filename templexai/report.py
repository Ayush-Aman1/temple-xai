"""Assemble docs/RESULTS.md and the README results block from the metrics files written by code (no hand-typed numbers)."""
from __future__ import annotations

import json
import re
from pathlib import Path

R = Path("experiments/results")


def _read(p: Path) -> str:
    return p.read_text() if p.exists() else f"_{p} not generated yet (run `make eval`)._\n"


def p4_table() -> str:
    p = Path("artifacts/p4/metrics.json")
    if not p.exists():
        return "_artifacts/p4/metrics.json missing (run `make p4`)._\n"
    m = json.loads(p.read_text())
    L = ["| model (frozen-feature heads, 3 seeds) | accuracy | macro-F1 |", "|---|---|---|"]
    names = {"cnn_only": "CNN features only", "fusion": "CNN ⊕ component vector (serving model)", "parts_gb": "components only, gradient boosting", "parts_mlp": "components only, MLP"}
    for k, n in names.items():
        v = m[k]
        L.append(f"| {n} | {v['mean_test_acc']:.3f} ± {v['std_test_acc']:.3f} | {v['mean_test_macro_f1']:.3f} ± {v['std_test_macro_f1']:.3f} |")
    a = m["A_finetuned_ref"]["test"]
    L.append(f"| reference: A fine-tuned end-to-end (J2, selected seed) | {a['accuracy']:.3f} | {a['macro_f1']:.3f} |")
    mc = m["mcnemar_fusion_vs_cnn_only"]
    mf = m["mcnemar_fusion_vs_A_finetuned"]
    L += ["", f"McNemar (exact), CNN-only vs fusion: CNN-only right/fusion wrong = {mc['b']}, fusion right/CNN-only wrong = {mc['c']}, p = {mc['p_value']:.3f}. "
          f"Fine-tuned A vs fusion: {mf['b']} / {mf['c']}, p = {mf['p_value']:.3f}. Image-level tests; images of one temple are correlated, so p-values are optimistic."]
    return "\n".join(L) + "\n"


def build() -> str:
    tr = Path("artifacts/TRAINING_REPORT.md").read_text() if Path("artifacts/TRAINING_REPORT.md").exists() else ""
    ds = re.search(r"## Dataset.*?(?=## J1)", tr, re.S)
    det = re.search(r"## J3.*?(?=## Method)", tr, re.S)
    parts = ["# Results (generated by `make report` from experiments/results/ and artifacts/; do not edit)", "",
             (ds.group(0) if ds else ""), "## Ablation A–D (test split, mean ± std over seeds)", "", _read(R / "ablation.md").split("\n", 2)[2],
             "## P4 fusion and part-based models", "", p4_table(), (det.group(0) if det else ""),
             "## Explanation evaluation", "", _read(R / "explanations" / "explanations.md").split("\n", 1)[1],
             "![faithfulness curves](../experiments/results/explanations/faithfulness_curves.png)", "",
             "## Robustness", "", _read(R / "robustness.md").split("\n", 1)[1], "![robustness](../experiments/results/robustness.png)", ""]
    return "\n".join(parts)


def update_manifest() -> None:
    """Add/refresh the BUILD-phase entries of artifacts/MANIFEST.json (modes, data hash, commit, headline metrics from files)."""
    import datetime

    from templexai.models.serving import git_commit

    mp = Path("artifacts/MANIFEST.json")
    man = json.loads(mp.read_text())
    base = man["items"][0]
    keep = [i for i in man["items"] if i.get("stage") != "BUILD"]
    modes = {"label_mode": base["label_mode"], "knowledge_mode": "MACHINE_COMPILED", "gold_eval": "UNAVAILABLE", "compute": "local_mps",
             "data_hash": base["data_hash"], "git_commit": git_commit(), "date": datetime.date.today().isoformat(), "stage": "BUILD"}
    new = []
    p4 = Path("artifacts/p4/metrics.json")
    if p4.exists():
        m = json.loads(p4.read_text())
        new.append({"path": "artifacts/p4", "kind": "fusion + part-based heads", "detector_mode": "DISTILLED",
                    "metrics": {k: {"acc": v["mean_test_acc"], "macro_f1": v["mean_test_macro_f1"]} for k, v in m.items() if isinstance(v, dict) and "mean_test_acc" in v}, **modes})
    ex = R / "explanations" / "summary.json"
    if ex.exists():
        new.append({"path": "experiments/results/explanations/summary.json", "kind": "explanation evaluation (ground-truth-free)", "detector_mode": "DISTILLED", **modes})
    for f, k in (("ablation.csv", "ablation"), ("robustness.csv", "robustness")):
        if (R / f).exists():
            new.append({"path": f"experiments/results/{f}", "kind": k, "detector_mode": "DISTILLED", **modes})
    new.append({"path": "templexai/knowledge/taxonomy.yaml", "kind": "knowledge layer", **{**modes, "knowledge_mode": "MACHINE_COMPILED"}})
    man["items"] = keep + new
    mp.write_text(json.dumps(man, indent=1))


def main() -> None:
    update_manifest()
    text = build()
    Path("docs/RESULTS.md").write_text(text)
    rd = Path("README.md")
    if rd.exists():
        s = rd.read_text()
        block = text.split("\n", 2)[2].replace("](../", "](")
        s = re.sub(r"<!-- RESULTS:START -->.*<!-- RESULTS:END -->", lambda _: "<!-- RESULTS:START -->\n" + block + "\n<!-- RESULTS:END -->", s, flags=re.S)
        rd.write_text(s)
    print("report written")


if __name__ == "__main__":
    main()
