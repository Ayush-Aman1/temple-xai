"""Verify every style_map rule against a fetched Wikipedia page; write the evidence to docs/METHOD.md.

A rule is kept only if the fetched page text contains one of its verify_keywords (EXCLUDE rules are always
kept - excluding is conservative - but are marked as such). The quoted sentence is <= 25 words.
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

from .common import get_json, today

API = "https://en.wikipedia.org/w/api.php"


def fetch_text(title: str, cache: Path) -> tuple[str, str]:
    d = get_json(API, {"action": "query", "prop": "extracts", "explaintext": 1, "redirects": 1,
                       "titles": title, "format": "json", "formatversion": 2}, cache)
    pages = d["query"]["pages"]
    p = pages[0]
    return p.get("extract", "") or "", "https://en.wikipedia.org/wiki/" + p.get("title", title).replace(" ", "_")


def quote(text: str, kw: str) -> str | None:
    for sent in re.split(r"(?<=[.!?])\s+", text):
        if kw.lower() in sent.lower():
            words = sent.split()
            return " ".join(words[:25]) + (" …" if len(words) > 25 else "")
    return None


def main(cfg_path: str = "configs/style_map.yaml", cache_dir: str = "data/cache/wikipedia_extracts") -> None:
    cfg = yaml.safe_load(Path(cfg_path).read_text())
    rows, ok_ids = [], []
    for r in cfg["rules"]:
        text, url = fetch_text(r["source_page"], Path(cache_dir))
        q, hit = None, None
        for kw in r["verify_keywords"]:
            q = quote(text, kw)
            if q:
                hit = kw
                break
        verified = q is not None
        keep = verified or r["tradition"] == "EXCLUDE"
        if keep:
            ok_ids.append(r["id"])
        rows.append((r["id"], r["tradition"], r["source_page"], url, hit, q, verified, keep))
    Path("configs/style_map_verified.yaml").write_text(yaml.safe_dump({"verified_rule_ids": ok_ids, "retrieved": today()}))
    md = ["## Style-label mapping evidence (auto-generated by `python -m templexai.data.verify_style_map`)", "",
          f"Retrieved {today()} from English Wikipedia via the MediaWiki API. A rule is kept only if the fetched "
          "page contains a verification keyword; EXCLUDE rules are always kept (conservative).", "",
          "| rule | → tradition | source page | keyword | quote (≤25 words) | verified | kept |", "|---|---|---|---|---|---|---|"]
    for rid, trad, page, url, hit, q, v, k in rows:
        md.append(f"| {rid} | {trad} | [{page}]({url}) | {hit or '—'} | {(q or '—').replace('|', '/')} | {v} | {k} |")
    Path("docs").mkdir(exist_ok=True)
    out = Path("docs/style_map_evidence.md")
    out.write_text("\n".join(md) + "\n")
    print(f"verified {sum(1 for r in rows if r[6])}/{len(rows)} rules; kept {len(ok_ids)}; evidence -> {out}")


if __name__ == "__main__":
    main()
